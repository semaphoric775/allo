"""Efinix Efinity project generation for vendor-neutral RTL (e.g., XLS output).

Efinity is located through ``$EFINITY_HOME`` (or ``efx_run`` on PATH). Its tools run
in a subshell that sources ``bin/setup.sh``, so the caller's environment (whose
PATH would otherwise be taken over by Efinity's bundled Python) stays untouched.
"""

import csv
import glob
import os
import re
import shutil
import subprocess
import xml.etree.ElementTree as ET

NS = {"efx": "http://www.efinixinc.com/enf_proj"}
EFX = "{%s}" % NS["efx"]


def efinity_home():
    """Efinity install directory, or None if not found."""
    home = os.environ.get("EFINITY_HOME")
    if not home and shutil.which("efx_run"):
        home = os.path.dirname(os.path.dirname(shutil.which("efx_run")))
    if home and os.path.isfile(os.path.join(home, "bin", "setup.sh")):
        return home
    return None


def is_available():
    return efinity_home() is not None


def _efx_run(args, cwd, timeout):
    home = efinity_home()
    if home is None:
        raise RuntimeError("Efinity not found. Set EFINITY_HOME to its install dir.")
    script = 'source "$0/bin/setup.sh" >/dev/null 2>&1 && exec efx_run "$@"'
    return subprocess.run(
        ["bash", "-c", script, home, *args],
        cwd=cwd,
        capture_output=True,
        text=True,
        timeout=timeout,
        check=False,
    )


def _template_xml():
    """An installed example project (non-unified flow) to use as a schema template.

    Efinity's project format is version specific and undocumented, so patching a
    project shipped with the installed release keeps the output loadable.
    """
    home = efinity_home()
    if home is None:
        raise RuntimeError("Efinity not found. Set EFINITY_HOME to its install dir.")
    for xml in sorted(glob.glob(os.path.join(home, "examples", "*", "*.xml"))):
        with open(xml, encoding="utf-8") as f:
            text = f.read()
        if "<efx:project" in text and 'unified_flow="false"' in text:
            return xml
    raise RuntimeError(f"No non-unified Efinity example project found in {home}")


def gen_project(out_dir, top, sources, *, family="Titanium", device="Ti60F225", **kw):
    """Write ``<top>.xml`` and ``<top>.sdc`` into ``out_dir`` with copies of ``sources``.

    Keyword options: ``timing_model`` (default "C4"), ``clock_mhz`` (default 100),
    ``clock_port`` (default "clk"; the clock is always named ``clk`` in the SDC).
    """
    os.makedirs(out_dir, exist_ok=True)
    names = []
    for src in sources:
        dst = os.path.join(out_dir, os.path.basename(src))
        if os.path.abspath(src) != os.path.abspath(dst):
            shutil.copy(src, dst)
        names.append(os.path.basename(src))

    ET.register_namespace("efx", NS["efx"])
    tree = ET.parse(_template_xml())
    root = tree.getroot()
    root.set("name", top)
    root.set("description", "Generated by Allo")
    for attr in ("last_run_state", "last_run_flow", "last_change"):
        root.attrib.pop(attr, None)
    dev = root.find("efx:device_info", NS)
    dev.find("efx:family", NS).set("name", family)
    dev.find("efx:device", NS).set("name", device)
    dev.find("efx:timing_model", NS).set("name", kw.get("timing_model", "C4"))
    design = root.find("efx:design_info", NS)
    design.find("efx:top_module", NS).set("name", top)
    for f in design.findall("efx:design_file", NS):
        design.remove(f)
    for i, n in enumerate(names):
        design.insert(
            1 + i,
            ET.Element(
                f"{EFX}design_file", name=n, version="default", library="default"
            ),
        )
    cons = root.find("efx:constraint_info", NS)
    for c in list(cons):
        cons.remove(c)
    ET.SubElement(cons, f"{EFX}sdc_file", name=f"{top}.sdc")
    ET.SubElement(cons, f"{EFX}inter_file", name="")
    # Drop example-specific sections (simulation, debugger, IP, ...)
    for tag in ("sim_info", "misc_info", "ip_info", "ooc_info", "debug_info"):
        node = root.find(f"efx:{tag}", NS)
        if node is not None:
            for c in list(node):
                node.remove(c)
    xml = os.path.join(out_dir, f"{top}.xml")
    tree.write(xml, encoding="UTF-8", xml_declaration=True)

    period = 1000.0 / kw.get("clock_mhz", 100.0)
    with open(os.path.join(out_dir, f"{top}.sdc"), "w", encoding="utf-8") as f:
        port = kw.get("clock_port", "clk")
        f.write(f"create_clock -period {period:.3f} -name clk [get_ports {{{port}}}]\n")
    return xml


# Efinity stages in order; each stage needs the outputs of the previous ones.
FLOW_STAGES = ("map", "pnr")


def run_flow(out_dir, top, flow="map", timeout=3600):
    """Run Efinity up to ``flow`` (see FLOW_STAGES); return top-level resources
    (plus ``fmax_mhz`` once place and route has run)."""
    if flow not in FLOW_STAGES:
        raise ValueError(f"flow must be one of {FLOW_STAGES}, got {flow!r}")
    for stage in FLOW_STAGES[: FLOW_STAGES.index(flow) + 1]:
        res = _efx_run([f"{top}.xml", "--prj", "--flow", stage], out_dir, timeout)
        if res.returncode != 0 or "FAIL" in res.stdout:
            log = os.path.join(out_dir, "outflow", f"{top}.err.log")
            raise RuntimeError(
                f"Efinity {stage} failed (see {log}):\n{res.stdout}\n{res.stderr}"
            )
    report = parse_resources(os.path.join(out_dir, "outflow", f"{top}.res.csv"))
    timing = os.path.join(out_dir, "outflow", f"{top}.timing.rpt")
    if flow != "map" and os.path.exists(timing):
        report["fmax_mhz"] = parse_fmax(timing)
    return report


def parse_fmax(timing_rpt):
    """Max achievable frequency (MHz) of the ``clk`` domain from Efinity's report."""
    with open(timing_rpt, encoding="utf-8") as f:
        text = f.read()
    m = re.search(
        r"Maximum possible analyzed clocks frequency.*?\n\s*clk\s+[\d.]+\s+([\d.]+)",
        text,
        re.S,
    )
    return float(m.group(1)) if m else None


def parse_resources(csv_path):
    """Return the top-level row of Efinity's resource estimate as {column: int}."""
    with open(csv_path, encoding="utf-8") as f:
        rows = [r for r in csv.reader(f, delimiter="\t") if len(r) > 2]
    header, top = rows[0], rows[1]
    return {
        h.strip(): int(v.strip().split("(")[0])
        for h, v in zip(header[1:], top[1:])
        if h.strip() and v.strip()
    }
